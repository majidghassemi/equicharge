r"""Emit LaTeX table snippets for the paper from ``results/results.json``.

Guarantees the paper's numbers are exactly the released run's numbers. Writes:
* ``paper/tables/learned_table.tex``  -- the unified baseline + learned benchmark.

Run after ``run_experiments`` and ``summarize_results``.
"""

from __future__ import annotations

import json
import os

HERE = os.path.dirname(__file__)
RESULTS = os.path.join(HERE, "results", "results.json")
TABLES = os.path.join(os.path.dirname(HERE), "paper", "tables")


def _med(d, k, dec=3):
    if f"{k}_median" in d:
        return f"{d[f'{k}_median']:.{dec}f}"
    v = d.get(k)
    return f"{v:.{dec}f}" if isinstance(v, (int, float)) else "n/a"


def baseline_table(R) -> str:
    """Body table: non-learned baselines vs the oracle ceiling (no RL in the body)."""
    base = R.get("baselines", {})
    o = R.get("oracle", {})
    lines = [
        "% Auto-generated by experiments/make_paper_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Non-learned online baselines on the scarce site, against the "
        "clairvoyant oracle ceiling. No online policy reaches positive worst decile "
        "satisfaction, far below the oracle. This online to offline gap is the open "
        "problem the released benchmark defines.}",
        "\\label{tabrl}",
        "\\begin{tabular}{lcccc}", "\\toprule",
        "policy & profit & mean sat & Gini & worst 10\\% \\\\", "\\midrule",
    ]
    for name in ["max_charge", "least_laxity", "proportional_fair", "saffe", "random"]:
        if name in base:
            d = base[name]
            lines.append(
                f"{name.replace('_',' ')} & {d['profit_mean']:.0f} & "
                f"{d['served_mean_sat']:.2f} & {d['gini']:.2f} & {d['worst10_sat']:.2f} \\\\")
    if isinstance(o.get("maximin"), dict):
        lines.append("\\midrule")
        mm = o["maximin"]
        lines.append(
            f"oracle ceiling (maximin) & -- & {mm['mean_satisfaction']:.2f} & -- & "
            f"{mm['worst_segment_mean']:.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def learned_table(R) -> str:
    """Appendix table: preliminary learned policies (dominated by random; undertrained)."""
    base = R.get("baselines", {})
    trained = R.get("trained", {})
    nseed = R.get("meta", {}).get("seeds", "?")
    lines = [
        "% Auto-generated by experiments/make_paper_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Preliminary learned policies at the "
        f"{R.get('meta',{}).get('timesteps',0):,}-timestep budget, median over {nseed} "
        "seeds, with the random and max-charge baselines for reference. Every learned "
        "policy is Pareto dominated by random. A learning-curve diagnostic (Fig. "
        "\\ref{figcurve}) shows this is undertraining, not a plateau. We do not present "
        "these as a result.}",
        "\\label{tabrlappendix}",
        "\\begin{tabular}{llcccc}", "\\toprule",
        "policy & kind & profit & mean sat & Gini & worst 10\\% \\\\", "\\midrule",
    ]
    for name in ["random", "max_charge"]:
        if name in base:
            d = base[name]
            lines.append(
                f"{name.replace('_',' ')} & baseline & {d['profit_mean']:.0f} & "
                f"{d['served_mean_sat']:.2f} & {d['gini']:.2f} & {d['worst10_sat']:.2f} \\\\")
    lines.append("\\midrule")
    order = ["profit_ppo", "util_l050", "util_l100", "egal_l025", "egal_l050",
             "egal_l075", "egal_l100"]
    names = {"profit_ppo": "profit PPO ($\\lambda=0$)",
             "util_l050": "utilitarian ($\\lambda=0.5$)",
             "util_l100": "utilitarian ($\\lambda=1$)",
             "egal_l025": "egalitarian ($\\lambda=0.25$)",
             "egal_l050": "egalitarian ($\\lambda=0.5$)",
             "egal_l075": "egalitarian ($\\lambda=0.75$)",
             "egal_l100": "egalitarian ($\\lambda=1$)"}
    for k in order:
        if k not in trained:
            continue
        d = trained[k]
        pm = d.get("profit_mean_median", d.get("profit_mean", float("nan")))
        lines.append(
            f"{names[k]} & learned & {pm:.0f} & {_med(d,'served_mean_sat',2)} & "
            f"{_med(d,'gini',2)} & {_med(d,'worst10_sat',2)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def check_table():
    """Body table: the surviving RL result on HONEST (inclusive) axes vs heuristics,
    n=10, from results/check.json. Rejection column is the survivorship control."""
    import numpy as np
    p = os.path.join(HERE, "results", "check.json")
    if not os.path.exists(p):
        return None
    d = json.load(open(p)); seeds = d["seeds"]; n = len(seeds)
    def med(k): return float(np.median([s[k] for s in seeds]))
    def wr(k, hib): return sum((s[k] > d["baselines"]["max_charge"][k]) == hib for s in seeds)
    rows = ["% Auto-generated by experiments/make_paper_tables.py -- do not edit.",
            "\\begin{table}[t]", "\\centering",
            "\\caption{A welfare-shaped learned controller ($\\lambda{=}0.5$, 3M steps, "
            f"median over {n} seeds) against the non-learned heuristics, on the paper's "
            "INCLUSIVE metrics (rejected drivers count as zero). The learned controller "
            "beats the strongest heuristic (max charge) on every axis, and rejects "
            "\\emph{fewer} drivers, so the service win is not survivorship. Win rate is "
            f"the fraction of {n} seeds beating max charge on that axis.}}",
            "\\label{tabcheck}",
            "\\begin{tabular}{lccc}", "\\toprule",
            "metric & learned ($\\lambda{=}0.5$) & max charge & win rate \\\\", "\\midrule"]
    mc = d["baselines"]["max_charge"]
    specs = [("profit (EUR/day)", "profit_mean", True, "%.0f"),
             ("inclusive satisfaction", "inclusive_mean_sat", True, "%.3f"),
             ("Gini (inclusive)", "gini", False, "%.3f"),
             ("rejection rate", "rejection_rate", False, "%.3f"),
             ("inclusive welfare", "welfare_mean", True, "%.3f")]
    for lab, k, hib, fmt in specs:
        rows.append(f"{lab} & {fmt % med(k)} & {fmt % mc[k]} & {wr(k, hib)}/{n} \\\\")
    a = d["analysis"]
    rows += ["\\midrule",
             f"\\multicolumn{{4}}{{l}}{{dominate all four axes at once: "
             f"{a['dominate_all4_seeds']}/{n} seeds}} \\\\",
             "\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(rows)


def main():
    os.makedirs(TABLES, exist_ok=True)
    R = json.load(open(RESULTS))
    for name, fn in [("baseline_table.tex", baseline_table),
                     ("learned_table.tex", learned_table)]:
        with open(os.path.join(TABLES, name), "w") as f:
            f.write(fn(R))
        print("wrote", os.path.join(TABLES, name))
    ct = check_table()
    if ct:
        with open(os.path.join(TABLES, "check_table.tex"), "w") as f:
            f.write(ct)
        print("wrote", os.path.join(TABLES, "check_table.tex"))


if __name__ == "__main__":
    main()
